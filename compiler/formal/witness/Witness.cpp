struct SignalInfo { std::string name; bool input = false; };

std::unordered_map<uint64_t, SignalInfo> read_signals(
    const std::filesystem::path& model) {
    std::unordered_map<uint64_t, SignalInfo> result;
    std::ifstream input(model);
    std::string line;
    while (std::getline(input, line)) {
        std::istringstream fields(line);
        uint64_t id = 0;
        std::string opcode;
        std::string sort;
        std::string name;
        if (!(fields >> id >> opcode >> sort >> name)) continue;
        if (opcode == "input" || opcode == "state")
            result[id] = {name, opcode == "input"};
    }
    return result;
}

std::string vcd_id(uint64_t id) { return "v" + std::to_string(id); }

std::string vcd_name(std::string name) {
    for (auto& character : name)
        if (!std::isalnum(static_cast<unsigned char>(character)) &&
            character != '_' && character != '$') character = '_';
    if (name.empty()) return "signal";
    return name;
}
